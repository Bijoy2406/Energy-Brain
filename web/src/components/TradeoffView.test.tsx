it.each([422, 503])('shows the API error message for HTTP %s and retries', async status => {
  const fetcher = vi.fn(async () => json({ detail: { code: 'unavailable', message: 'Specific API message' } }, status))
  vi.stubGlobal('fetch', fetcher)
  render(<TradeoffView {...props()} />)
  expect(await screen.findByRole('alert')).toHaveTextContent('Specific API message')
  fetcher.mockResolvedValue(json(paretoFixture()))
  fireEvent.click(screen.getByRole('button', { name: 'Retry' }))
  expect(await screen.findByText(/From the cheapest/)).toBeVisible()
  expect(fetcher).toHaveBeenCalledTimes(2)
})
it('counts down the API rate limit before enabling Retry', async () => {
  vi.useFakeTimers()
  vi.stubGlobal('fetch', vi.fn(async () => json({ detail: { code: 'rate_limited', message: 'Please wait', retry_after_s: 2 } }, 429)))
  render(<TradeoffView {...props()} />)
  await act(async () => {})
  expect(screen.getByRole('button', { name: 'Retry' })).toBeDisabled()
  expect(screen.getByRole('status')).toHaveTextContent('2 seconds')
  await act(async () => { vi.advanceTimersByTime(1000) })
  expect(screen.getByRole('status')).toHaveTextContent('1 seconds')
  await act(async () => { vi.advanceTimersByTime(1000) })
  expect(screen.getByRole('button', { name: 'Retry' })).toBeEnabled()
})
